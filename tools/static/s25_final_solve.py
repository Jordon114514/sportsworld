def uleb_at(o):
    if o < 0 or o+1 >= N: return None, o
    r = sh = 0; p = o
    for _ in range(5):
        if p >= N: return None, p
        b = s[p]; p += 1
        r |= (b & 0x7f) << sh
        if not b & 0x80: return r, p
        sh += 7
    return None, p

def valid(o):
    ln, p = uleb_at(o)
    if ln is None or ln <= 0 or ln > 2048 or p + ln >= N: return False
    if s[p+ln] != 0: return False
    body = s[p:p+ln]
    i = 0
    while i < len(body):
        b = body[i]
        if b == 0: return False
        if b < 0x80: i += 1
        elif (b & 0xE0) == 0xC0 and i+1 < len(body) and (body[i+1] & 0xC0) == 0x80: i += 2
        elif (b & 0xF0) == 0xE0 and i+2 < len(body) and (body[i+1] & 0xC0) == 0x80 and (body[i+2] & 0xC0) == 0x80: i += 3
        else: return False
    return True

